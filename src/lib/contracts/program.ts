import { z } from "zod"

/*
 * Request and response shapes for /api/program and /api/sessions, shared by
 * the app and the API. No server-only imports: bundled into the app.
 */

const isoDate = z.string().regex(/^\d{4}-\d{2}-\d{2}$/, "Use YYYY-MM-DD")

const programSchema = z.object({
  id: z.uuid(),
  status: z.enum([
    "active",
    "paused",
    "completed",
    "stopped_referred",
  ]),
  /** The content version the program runs on; fetch it from /api/content/:id. */
  contentVersionId: z.uuid(),
  trackId: z.string(),
  currentPhase: z.string(),
  startedAt: z.iso.datetime({ offset: true }),
  progress: z.object({
    /** Sessions logged in the current phase; picks the next session. */
    completedInPhase: z.int().min(0),
    /** Local dates of the most recent sessions, newest first. */
    recentDates: z.array(isoDate),
  }),
})

/** The user's most recent program, whatever its status, or null before their first. */
const programResponseSchema = z.object({
  program: programSchema.nullable(),
})

const sessionLogRequestSchema = z.object({
  /** Generated by the app, so a retried or offline-synced log is recorded once. */
  id: z.uuid(),
  programId: z.uuid(),
  sessionId: z.string().min(1),
  phaseId: z.string().min(1),
  /** The user's local date. */
  scheduledDate: isoDate,
  completedAt: z.iso.datetime({ offset: true }),
  painAfter: z.int().min(0).max(10),
  exercises: z.array(z.object({
    position: z.int().min(0),
    exerciseId: z.string().min(1),
    completed: z.boolean(),
    setsDone: z.int().min(0),
  })).min(1),
})

const sessionLoggedSchema = z.object({
  id: z.uuid(),
  /** False when this log was already recorded, such as on a retry. */
  created: z.boolean(),
})

type ProgramSummary = z.infer<typeof programSchema>
type SessionLogRequest = z.infer<typeof sessionLogRequestSchema>

export {
  isoDate,
  programResponseSchema,
  programSchema,
  type ProgramSummary,
  sessionLoggedSchema,
  type SessionLogRequest,
  sessionLogRequestSchema,
}
